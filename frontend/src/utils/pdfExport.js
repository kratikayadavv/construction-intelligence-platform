import jsPDF from 'jspdf';

function saveReport(title, result, notes = '') {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 42, width = doc.internal.pageSize.getWidth() - margin * 2;
  let y = 52;
  doc.setFont('helvetica', 'bold'); doc.setFontSize(18); doc.text(title, margin, y); y += 28;
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10);
  doc.text('Generated by Multimodal Construction Intelligence Platform', margin, y); y += 22;
  if (notes) { doc.setFont('helvetica', 'bold'); doc.text('Inspector notes', margin, y); y += 14; doc.setFont('helvetica', 'normal'); const lines = doc.splitTextToSize(notes, width); doc.text(lines, margin, y); y += lines.length * 13 + 12; }
  const entries = Object.entries(result || {});
  for (const [key, value] of entries) {
    const label = key.replaceAll('_', ' ').replace(/^./, s => s.toUpperCase());
    const body = Array.isArray(value) ? value.map(v => typeof v === 'object' ? JSON.stringify(v) : String(v)).join('\n• ') : typeof value === 'object' && value !== null ? JSON.stringify(value, null, 2) : String(value ?? '');
    const lines = doc.splitTextToSize(body || '—', width - 4);
    if (y + 22 + lines.length * 12 > doc.internal.pageSize.getHeight() - 44) { doc.addPage(); y = 48; }
    doc.setFont('helvetica', 'bold'); doc.setFontSize(11); doc.text(label, margin, y); y += 15;
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9);
    const chunks = [];
    for (const line of lines) {
      if (y > doc.internal.pageSize.getHeight() - 42) { doc.addPage(); y = 48; }
      doc.text(line, margin, y); y += 12;
    }
    y += 8;
  }
  doc.save(`${title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${Date.now()}.pdf`);
}
export const exportSafetyPDF = (result, notes) => saveReport('Site Safety Inspection Report', result, notes);
export const exportCrackPDF = (result, notes) => saveReport('Structural Crack Diagnostic Report', result, notes);
